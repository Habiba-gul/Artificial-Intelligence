# double ended queue -> deque
# queue :
# insertion from rear
# deletion from front
# deque:
# insertion from front +rear
# deletion from front +rear
# two types of deque
# 1) restricted input deque -> insertion from front not allowed
# 2) restricted output deque ->deletion from rear is not allowed
# operations of deque:
# isempty() , isfull() ,enquef(),enqueur(),dequeuf(),dequeur()